class ResearchFindingRead(BaseModel):
    """Schema for reading research finding data"""
    id: int
    deal_id: int
    category: Optional[str]
    source_type: Optional[str]
    content: str
    citation: Optional[str]
    created_at: datetime

    class Config:
        from_attributes = True
