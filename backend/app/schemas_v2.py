class ResearchFindingCreate(BaseModel):
    """Schema for creating a research finding"""
    deal_id: int = Field(..., description="ID of the deal this finding belongs to")
    category: Optional[str] = Field(None, max_length=100, description="Finding category: facts, metrics, market, competition, etc.")
