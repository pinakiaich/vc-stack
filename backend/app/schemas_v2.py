"""
Pydantic schemas for VC-Stack v2 API endpoints
"""
from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from datetime import datetime


# ============================================================================
# Deal Schemas
# ============================================================================

class DealCreate(BaseModel):
    """Schema for creating a new deal"""
    name: str = Field(..., min_length=1, max_length=255, description="Deal name")
    source: Optional[str] = Field(None, max_length=255, description="How the deal was sourced")
    owner: Optional[str] = Field(None, max_length=100, description="Deal owner/analyst")
    sector: Optional[str] = Field(None, max_length=100, description="Industry sector")
    stage: Optional[str] = Field(None, max_length=100, description="Investment stage")
    status: Optional[str] = Field("active", max_length=50, description="Deal status")


class DealRead(BaseModel):
    """Schema for reading deal data"""
    id: int
    name: str
    source: Optional[str]
    owner: Optional[str]
    sector: Optional[str]
    stage: Optional[str]
    status: str
    created_at: datetime

    class Config:
        from_attributes = True


# ============================================================================
# Memo Schemas
# ============================================================================

class MemoCreate(BaseModel):
    """Schema for creating a memo"""
    deal_id: int = Field(..., description="ID of the deal this memo belongs to")
    memo_type: str = Field(..., max_length=50, description="Type of memo: screening, ic, diligence")
    version: Optional[int] = Field(1, description="Memo version number")
    json_payload: Optional[str] = Field(None, description="JSON content of the memo")
    generated_by_agent: Optional[bool] = Field(True, description="Whether generated by AI agent")
    confidence_score: Optional[float] = Field(None, ge=0.0, le=1.0, description="Confidence score 0-1")


class MemoRead(BaseModel):
    """Schema for reading memo data"""
    id: int
    deal_id: int
    memo_type: str
    version: int
    json_payload: Optional[str]
    generated_by_agent: bool
    confidence_score: Optional[float]
    created_at: datetime

    class Config:
        from_attributes = True


# ============================================================================
