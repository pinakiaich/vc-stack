# ============================================================================
# Data Room Document Schemas
# ============================================================================

class DataRoomDocumentCreate(BaseModel):
    """Schema for creating a data room document"""
    deal_id: int = Field(..., description="ID of the deal this document belongs to")
    filename: str = Field(..., min_length=1, max_length=255, description="Document filename")
    doc_type: Optional[str] = Field(None, max_length=50, description="Document type: pdf, md, txt, excel, etc.")
    source: Optional[str] = Field("company", max_length=100, description="Document source")
    embedding_id: Optional[str] = Field(None, max_length=255, description="Reference to embedding/chunk ID")


class DataRoomDocumentRead(BaseModel):
    """Schema for reading data room document data"""
    id: int
    deal_id: int
    filename: str
    doc_type: Optional[str]
    source: str
    embedding_id: Optional[str]
    created_at: datetime

    class Config:
        from_attributes = True


# ============================================================================
# External Source Schemas
# ============================================================================

class ExternalSourceCreate(BaseModel):
    """Schema for creating an external source"""
    deal_id: int = Field(..., description="ID of the deal this source belongs to")
    url: str = Field(..., min_length=1, max_length=500, description="Source URL")
